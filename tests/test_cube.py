"""Cube engine checks (docs/testing.md, "Mathematical correctness").

Expected states come from tests/fixtures/cube/reference_sequences.json, generated by an independent
engine (Kociemba's RubikTwoPhase), and from hand-derived facts; never from this engine.
"""
import json
import random
from pathlib import Path

import pytest

from cubetrack.cube import SOLVED, SOLVED_FACELETS, CubeState, apply_moves, facelets_to_state, invert_sequence
from cubetrack.cube import parse_moves, state_to_facelets, validate_facelets
from cubetrack.cube.facelets import CORNER_FACELETS, EDGE_FACELETS, idx
from cubetrack.cube.moves import MOVES
from cubetrack.cube.net import state_net

pytestmark = pytest.mark.foundation

REFERENCE = json.loads((Path(__file__).parent / "fixtures" / "cube" / "reference_sequences.json").read_text())
FACES = "URFDLB"
QUARTERS = list(FACES)
ALL_MOVES = [f + s for f in FACES for s in ("", "'", "2")]
SEED = 20261018


# ---------- independent expected states ----------

@pytest.mark.parametrize("case", REFERENCE["cases"], ids=lambda c: c["sequence"][:40])
def test_matches_independent_reference_engine(case):
    assert state_to_facelets(apply_moves(SOLVED, case["sequence"])) == case["facelets"]


def test_r_from_solved_matches_the_hand_checked_fixture():
    # docs/conventions.md: R carries F's right column up to U; B's column next to R now shows U.
    assert state_to_facelets(MOVES["R"]) == "UUFUUFUUFRRRRRRRRRFFDFFDFFDDDBDDBDDBLLLLLLLLLUBBUBBUBB"


def test_u_turn_by_hand():
    f = state_to_facelets(MOVES["U"])
    # U clockwise from above: the F top row moves to L, R's to F, B's to R, L's to B.
    assert f[idx("F1"):idx("F3") + 1] == "RRR"
    assert f[idx("L1"):idx("L3") + 1] == "FFF"
    assert f[idx("B1"):idx("B3") + 1] == "LLL"
    assert f[idx("R1"):idx("R3") + 1] == "BBB"
    assert f[:9] == "U" * 9


# ---------- identities and structure ----------

@pytest.mark.parametrize("move", ALL_MOVES)
def test_move_then_inverse_restores(move):
    assert apply_moves(SOLVED, [move] + invert_sequence([move])) == SOLVED


@pytest.mark.parametrize("face", QUARTERS)
def test_quarter_turn_identities(face):
    q, inv, half = MOVES[face], MOVES[face + "'"], MOVES[face + "2"]
    assert q * q * q * q == SOLVED
    assert half * half == SOLVED
    assert q * q == half
    assert q * q * q == inv


@pytest.mark.parametrize("face", QUARTERS)
def test_quarter_turn_changes_exactly_four_corners_and_four_edges(face):
    m = MOVES[face]
    assert sum(m.cp[i] != i or m.co[i] for i in range(8)) == 4
    assert sum(m.ep[i] != i or m.eo[i] for i in range(12)) == 4


def test_sexy_move_six_times_is_identity():
    assert apply_moves(SOLVED, "R U R' U' " * 6) == SOLVED


def test_noncommuting_moves_differ():
    assert apply_moves(SOLVED, "R U") != apply_moves(SOLVED, "U R")


def test_random_sequences_keep_invariants_and_invert():
    rng = random.Random(SEED)
    for n in range(1000):
        seq = [rng.choice(ALL_MOVES) for _ in range(rng.randint(1, 40))]
        state = SOLVED
        for m in seq:
            state = state * MOVES[m]
            result = validate_facelets(state_to_facelets(state))
            assert result.status == "valid", f"seed {SEED} case {n}: {seq} -> {result.codes}"
        assert apply_moves(state, invert_sequence(seq)) == SOLVED, f"seed {SEED} case {n}: {seq}"
        assert facelets_to_state(state_to_facelets(state)) == state
        assert CubeState.from_dict(state.to_dict()) == state
        assert state * state.inverse() == SOLVED


def test_invert_sequence():
    assert invert_sequence(["R", "U'", "F2"]) == ["F2", "U", "R'"]


def test_states_are_immutable_values():
    s = apply_moves(SOLVED, "R")
    t = s * MOVES["U"]
    assert s == apply_moves(SOLVED, "R")  # applying a move made a new state
    with pytest.raises(AttributeError):
        s.cp = SOLVED.cp


