# ---------- validity of facelet input (constructed directly, never by moves) ----------

def set_facelets(base, changes):
    f = list(base)
    for i, ch in changes.items():
        f[i] = ch
    return "".join(f)


def twist_corner(facelets, slot, k=1):
    a, b, c = CORNER_FACELETS[slot]
    return set_facelets(facelets, {a: facelets[c], b: facelets[a], c: facelets[b]} if k == 1 else
                        {a: facelets[b], b: facelets[c], c: facelets[a]})


def flip_edge(facelets, slot):
    a, b = EDGE_FACELETS[slot]
    return set_facelets(facelets, {a: facelets[b], b: facelets[a]})


def swap(facelets, slots_a, slots_b):
    changes = {}
    for x, y in zip(slots_a, slots_b):
        changes[x], changes[y] = facelets[y], facelets[x]
    return set_facelets(facelets, changes)


def test_solved_and_generated_states_are_valid():
    assert validate_facelets(SOLVED_FACELETS).status == "valid"
    assert validate_facelets(state_to_facelets(apply_moves(SOLVED, "R U F' L2 D B'"))).status == "valid"


def test_one_twisted_corner():
    assert validate_facelets(twist_corner(SOLVED_FACELETS, 0)).codes == ["corner_twist"]


def test_one_flipped_edge():
    assert validate_facelets(flip_edge(SOLVED_FACELETS, 0)).codes == ["edge_flip"]


def test_two_edges_swapped():
    assert validate_facelets(swap(SOLVED_FACELETS, EDGE_FACELETS[0], EDGE_FACELETS[1])).codes == ["parity"]


def test_two_corners_swapped():
    assert validate_facelets(swap(SOLVED_FACELETS, CORNER_FACELETS[0], CORNER_FACELETS[1])).codes == ["parity"]


def test_two_edges_and_two_corners_swapped_is_valid():
    f = swap(SOLVED_FACELETS, EDGE_FACELETS[0], EDGE_FACELETS[1])
    assert validate_facelets(swap(f, CORNER_FACELETS[0], CORNER_FACELETS[1])).status == "valid"


def test_two_compensating_twists_and_two_flips_are_valid():
    f = twist_corner(twist_corner(SOLVED_FACELETS, 0, 1), 1, 2)
    assert validate_facelets(f).status == "valid"
    assert validate_facelets(flip_edge(flip_edge(SOLVED_FACELETS, 0), 5)).status == "valid"


def test_duplicate_edge_with_another_missing():
    a, b = EDGE_FACELETS[0], EDGE_FACELETS[1]  # put a copy of edge UR where UF was
    f = set_facelets(SOLVED_FACELETS, {b[0]: SOLVED_FACELETS[a[0]], b[1]: SOLVED_FACELETS[a[1]]})
    result = validate_facelets(f)
    assert "duplicate_edge" in result.codes and "missing_edge" in result.codes and result.status == "invalid"


def test_duplicate_corner_with_another_missing():
    a, b = CORNER_FACELETS[0], CORNER_FACELETS[1]
    f = set_facelets(SOLVED_FACELETS, {b[k]: SOLVED_FACELETS[a[k]] for k in range(3)})
    result = validate_facelets(f)
    assert "duplicate_corner" in result.codes and "missing_corner" in result.codes


def test_one_facelet_changed_breaks_color_count():
    result = validate_facelets(set_facelets(SOLVED_FACELETS, {idx("F1"): "R"}))
    assert result.codes[0] == "color_count" and result.status == "invalid"


def test_edge_with_opposite_colors_is_not_a_piece():
    a, b = EDGE_FACELETS[1]  # UF edge -> U and D: opposite faces never share an edge
    d_edge = EDGE_FACELETS[5]  # DF edge -> give it U/F so color counts stay 9
    f = set_facelets(SOLVED_FACELETS, {b: "D", d_edge[0]: "F"})
    assert "invalid_edge" in validate_facelets(f).codes


def test_mirrored_corner_is_not_a_legal_twist():
    a, b, c = CORNER_FACELETS[0]  # URF read as U F R: same colors, mirrored order
    f = set_facelets(SOLVED_FACELETS, {b: SOLVED_FACELETS[c], c: SOLVED_FACELETS[b]})
    result = validate_facelets(f)
    assert "invalid_corner" in result.codes and result.state is None


def test_partial_scan_is_incomplete_not_invalid():
    result = validate_facelets(set_facelets(SOLVED_FACELETS, {idx("F1"): "?", idx("R5"): "?"}))
    assert result.status == "incomplete"


@pytest.mark.parametrize("bad", ["U" * 53, "X" * 54, None, SOLVED_FACELETS.lower()])
def test_malformed_facelets_are_rejected_with_a_reason(bad):
    result = validate_facelets(bad)
    assert result.status == "invalid" and result.codes == ["malformed"]


def test_net_shows_u_on_top_and_lfrb_row():
    lines = state_net(SOLVED).splitlines()
    assert lines[0].strip() == "U U U" and lines[3] == "L L L  F F F  R R R  B B B" and lines[8].strip() == "D D D"
